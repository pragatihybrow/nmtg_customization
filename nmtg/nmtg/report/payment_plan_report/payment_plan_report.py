def execute(filters=None):
    filters = filters or {}
    data = get_data(filters)
    max_entries = 0
    for row in data:
        for key in row:
            if key.startswith("bd_pr_"):
                max_entries = max(max_entries, int(key.rsplit("_", 1)[1]))
    return get_columns(max_entries), data


